const char *pwn_oui_vendor(const uint8_t mac[6])
{
    if (!mac) {
        return "?";
    }
    if (pwn_oui_randomized(mac)) {
        return "randomized";
    }
    for (size_t i = 0; i < sizeof(s_ouis) / sizeof(s_ouis[0]); i++) {
        if (s_ouis[i].oui[0] == mac[0] &&
            s_ouis[i].oui[1] == mac[1] &&
            s_ouis[i].oui[2] == mac[2]) {
            return s_ouis[i].vendor;
        }
    }
    return "unknown";
}

bool pwn_oui_randomized(const uint8_t mac[6])
{
    return mac && (mac[0] & 0x02) != 0;
}
